def jsonl(rows):
    return "\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n"


def codex_session(day, turns, cwd="/Users/me/notes"):
    """turns: [用户的话, ...]，每句后面跟一句 AI 回复。"""
    rows = [
        {"timestamp": "2026-10-%02dT09:00:00Z" % day, "type": "session_meta", "payload": {"id": "s%d" % day, "cwd": cwd}},
        {"timestamp": "2026-10-%02dT09:00:01Z" % day, "type": "response_item", "payload": {"type": "message", "role": "user", "content": [{"type": "input_text", "text": "<environment_context>\n<cwd>%s</cwd>\n</environment_context>" % cwd}]}},
        {"timestamp": "2026-10-%02dT09:00:01Z" % day, "type": "response_item", "payload": {"type": "message", "role": "user", "content": [{"type": "input_text", "text": "# AGENTS.md instructions for %s\n\n秘密规则" % cwd}]}},
    ]
    for index, text in enumerate(turns):
        minute = 1 + index * 2
        rows.append({"timestamp": "2026-10-%02dT09:%02d:00Z" % (day, minute), "type": "event_msg", "payload": {"type": "user_message", "message": text}})
        rows.append({"timestamp": "2026-10-%02dT09:%02d:30Z" % (day, minute), "type": "event_msg", "payload": {"type": "agent_message", "message": "好的，已完成。"}})
    return jsonl(rows)


def claude_session(day, turns, cwd="/Users/me/app"):
    rows = [{"type": "user", "isMeta": True, "message": {"role": "user", "content": "Caveat: The messages below were generated by the user"}, "timestamp": "2026-10-%02dT10:00:00Z" % day, "cwd": cwd}]
    for index, text in enumerate(turns):
        rows.append({"type": "user", "message": {"role": "user", "content": text + "\n<system-reminder>内部提醒</system-reminder>"}, "timestamp": "2026-10-%02dT10:%02d:00Z" % (day, index * 2 + 1), "cwd": cwd})
        rows.append({"type": "assistant", "message": {"role": "assistant", "content": [{"type": "text", "text": "完成"}]}, "timestamp": "2026-10-%02dT10:%02d:30Z" % (day, index * 2 + 1), "cwd": cwd})
    return jsonl(rows)


def workbuddy_session(day, turns, cwd="/Users/me/WorkBuddy/2026-10"):
    rows = [{"type": "ai-title", "aiTitle": "对比", "sessionId": "w%d" % day, "cwd": cwd, "timestamp": "2026-10-%02dT11:00:00Z" % day}]
    for index, text in enumerate(turns):
        wrapped = "<system-reminder>记忆和技能提醒</system-reminder>\n<user_query>%s</user_query>\n<current_time>2026-10-%02d</current_time>" % (text, day)
        rows.append({"type": "message", "role": "user", "content": [{"type": "input_text", "text": wrapped}], "timestamp": "2026-10-%02dT11:%02d:00Z" % (day, index * 2 + 1), "cwd": cwd, "sessionId": "w%d" % day})
        rows.append({"type": "message", "role": "assistant", "status": "completed", "content": [{"type": "output_text", "text": "整理好了"}], "timestamp": "2026-10-%02dT11:%02d:30Z" % (day, index * 2 + 1), "cwd": cwd})
    return jsonl(rows)


class Machine:
    """在临时目录里搭一套假的主目录。"""

    def __init__(self, root):
        self.home = Path(root)
        sessions = self.home / ".codex" / "sessions" / "2026" / "10"
        xhs = [
            (2, ["把下面这段改成小红书风格：周末去了一家咖啡店，环境很好，适合看书。", "太长了，控制在 200 字"]),
            (5, ["帮我把这段写成小红书的风格：新买的跑鞋穿了一周，脚感很软。", "太长了，200 字以内"]),
            (8, ["改成小红书风格，多用短句：这次去杭州玩了三天，西湖边骑车最舒服。", "再短点，控制在 200 字"]),
            (11, ["把下面这段改成小红书风格：第一次自己做蛋糕，边缘有点焦。", "用中文回答"]),
        ]
        for day, turns in xhs:
            self.write(sessions / ("%02d" % day) / ("rollout-2026-10-%02d-xhs.jsonl" % day), codex_session(day, turns))
        # 同一个对话里反复改同一件事：不算重复
        self.write(sessions / "12" / "rollout-2026-10-12-bug.jsonl", codex_session(12, ["这个报错怎么回事：TypeError: Cannot read properties of undefined", "这个报错怎么回事：还是不行", "这个报错怎么回事：再看看"]))
        # 纠正跟在不同任务后面
        self.write(sessions / "13" / "rollout-2026-10-13-sql.jsonl", codex_session(13, ["为什么这个 SQL 很慢", "说中文"]))
        self.write(sessions / "14" / "rollout-2026-10-14-key.jsonl", codex_session(14, ["帮我检查这个配置能不能用：api_key=sk-abcdefghijklmnopqrstuvwxyz123456，手机 13812345678", "好的"]))
        self.write(self.home / ".codex" / "archived_sessions" / "rollout-2026-09-01-old.jsonl.zst", "压缩的内容")

        projects = self.home / ".claude" / "projects" / "-Users-me-app"
        self.write(projects / "a.jsonl", claude_session(6, ["给首页的图片加上懒加载", "请用中文回答"]))
        self.write(projects / "b.jsonl", claude_session(9, ["把 README 的安装步骤更新一下", "中文回复我"]))
        self.write(projects / "a" / "subagents" / "agent-1.jsonl", claude_session(9, ["子任务的话"]))

        wb = self.home / ".workbuddy" / "projects"
        competitors = [
            (3, ["按目标用户、核心功能、定价、优缺点四列对比这几个竞品：Notion、飞书文档、语雀"]),
            (7, ["按目标用户、核心功能、定价、优缺点四列对比：Figma、Sketch、即时设计", "记住，以后回答都先给结论"]),
            (10, ["按目标用户、核心功能、定价、优缺点四列对比：Cursor、Windsurf、Trae"]),
        ]
        for day, turns in competitors:
            self.write(wb / ("-Users-me-WorkBuddy-%02d" % day) / ("w%d.jsonl" % day), workbuddy_session(day, turns))
        self.write(self.home / ".codebuddy" / "history.jsonl", jsonl([{"display": "整理一下今天的会议纪要：讨论了排期", "pastedContents": {}, "timestamp": 1760600000000, "project": "/Users/me/app"}]))
        self.write(self.home / ".codex" / "AGENTS.md", "# 规则\n\n- 回答使用中文。\n- 不要使用 emoji。\n")

    def write(self, path, text):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def run(*args):
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        collect.main(list(args))
    return buffer.getvalue()


class ExtractTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.machine = Machine(Path(cls.tmp.name) / "home")
        cls.work = Path(cls.tmp.name) / "work"
        cls.scan = json.loads(run("--home", str(cls.machine.home), "scan"))
        cls.summary = json.loads(run("--home", str(cls.machine.home), "extract", "--out", str(cls.work)))
        cls.groups = json.loads((cls.work / "groups.json").read_text(encoding="utf-8"))
        cls.raw = (cls.work / "groups.json").read_text(encoding="utf-8")

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_scan_lists_sources_without_reading(self):
        tools = {source["tool"]: source for source in self.scan["sources"]}
        self.assertEqual(tools["codex"]["files"], 8)
        self.assertEqual(tools["codex"]["compressed"], 1)
        self.assertEqual(tools["claude-code"]["files"], 2)
        self.assertEqual(tools["workbuddy"]["files"], 3)
        self.assertIn("codebuddy", tools)

    def test_compressed_files_are_skipped_and_counted(self):
        if collect.shutil.which("zstd"):
            self.skipTest("本机装了 zstd")
        self.assertEqual(self.summary["tools"]["codex"]["skippedCompressed"], 1)

    def test_repeated_task_across_conversations(self):
        xhs = next(group for group in self.groups["tasks"] if "小红书" in group["center"])
        self.assertEqual(xhs["count"], 4)
        self.assertEqual(xhs["conversations"], 4)
        self.assertEqual(xhs["days"], 4)
        follow = {item["text"]: item for item in xhs["followUps"]}
        self.assertEqual(follow["控制在 200 字"]["count"], 2)
        self.assertTrue(follow["用中文回答"]["general"])

    def test_workbuddy_user_query_is_unwrapped(self):
        competitor = next(group for group in self.groups["tasks"] if "四列对比" in group["center"])
        self.assertEqual(competitor["count"], 3)
        self.assertEqual(competitor["tools"], {"workbuddy": 3})
        self.assertNotIn("current_time", json.dumps(competitor, ensure_ascii=False))

    def test_same_conversation_repeats_do_not_group(self):
        self.assertFalse(any("报错" in group["center"] for group in self.groups["tasks"]))

    def test_corrections_after_different_tasks(self):
        chinese = next(group for group in self.groups["corrections"] if group["id"] == "C-chinese")
        self.assertEqual(chinese["count"], 4)
        self.assertGreaterEqual(chinese["followsTaskKinds"], 3)
        self.assertEqual(set(chinese["tools"]), {"codex", "claude-code"})

    def test_standing_statement_kept_even_once(self):
        texts = [sample["text"] for group in self.groups["standing"] for sample in group["samples"]]
        self.assertIn("记住，以后回答都先给结论", texts)

    def test_injected_content_never_appears(self):
        for marker in ("environment_context", "AGENTS.md instructions", "秘密规则", "system-reminder", "内部提醒", "子任务的话", "Caveat"):
            self.assertNotIn(marker, self.raw)

    def test_secrets_are_hidden(self):
        self.assertNotIn("sk-abcdefghij", self.raw)
        self.assertNotIn("13812345678", self.raw)

    def test_show_prints_groups_and_members(self):
        text = run("show", "--work", str(self.work), "--kind", "tasks", "--limit", "5")
        self.assertIn("中心说法", text)
        xhs = next(group for group in self.groups["tasks"] if "小红书" in group["center"])
        detail = run("show", "--work", str(self.work), "--id", xhs["id"])
        self.assertEqual(detail.count("\n  - "), 4)

    def test_existing_rules_collected(self):
        run("--home", str(self.machine.home), "existing", "--work", str(self.work))
        existing = (self.work / "existing.md").read_text(encoding="utf-8")
        self.assertIn("回答使用中文", existing)


def candidate(**fields):
    base = {
        "type": "prompt",
        "title": "小红书风格改写",
        "content": "把下面这段改成小红书风格，控制在 200 字：\n{{内容}}",
        "reason": "4 个不同的日子里让 AI 改写小红书文案",
        "confidence": "medium",
        "scope": "global",
        "count": 4,
        "conversations": 4,
        "days": 4,
        "tools": ["codex"],
        "quotes": [{"tool": "codex", "at": "2026-10-11", "text": "把下面这段改成小红书风格：……", "after": "太长了，控制在 200 字"}],
    }
    base.update(fields)
    return base


class FinalizeTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self.tmp.name)
        (self.dir / "existing.md").write_text("## /Users/me/.codex/AGENTS.md\n\n- 回答使用中文。\n", encoding="utf-8")
        (self.dir / "summary.json").write_text(json.dumps({"conversations": 12, "userMessages": 30, "from": "2026-10-02", "to": "2026-10-14", "tools": {"codex": {"conversations": 8, "skippedCompressed": 1}}}), encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def finalize(self, candidates):
        draft = self.dir / "draft.json"
        draft.write_text(json.dumps({"candidates": candidates}, ensure_ascii=False), encoding="utf-8")
        out = self.dir / "out.json"
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            code = finalize.main([str(draft), "--work", str(self.dir), "--out", str(out)])
        return code, buffer.getvalue(), out

    def test_writes_file_with_header(self):
        code, text, out = self.finalize([candidate()])
        self.assertEqual(code, 0, text)
        data = json.loads(out.read_text(encoding="utf-8"))
        self.assertEqual((data["app"], data["kind"], data["formatVersion"]), ("promptbox", "candidates", 1))
        self.assertEqual(data["scanned"]["conversations"], 12)
        self.assertEqual(data["candidates"][0]["export"], {"format": "md"})

    def test_missing_reason_is_an_error_and_nothing_is_written(self):
        code, text, out = self.finalize([candidate(reason="")])
        self.assertEqual(code, 1)
        self.assertIn("缺少理由", text)
        self.assertFalse(out.exists())

    def test_low_confidence_dropped(self):
        code, _, out = self.finalize([candidate(), candidate(title="随便一条", content="总结一下", confidence="low")])
        self.assertEqual(code, 0)
        self.assertEqual(len(json.loads(out.read_text(encoding="utf-8"))["candidates"]), 1)

    def test_rule_scope_must_be_explicit_and_complete(self):
        rule = dict(type="rule", title="回答用中文", content="回答使用中文。")
        invalid = [candidate(**rule, scope=None), candidate(**rule, scope=[]), candidate(**rule, scope="other"),
                   candidate(**rule, scope="project"), candidate(**rule, scope="task", taskType="  ")]
        for entry in invalid:
            with self.subTest(scope=entry.get("scope")):
                code, _, out = self.finalize([entry])
                self.assertEqual(code, 1)
                self.assertFalse(out.exists())

    def test_prompts_have_no_scope(self):
        code, text, out = self.finalize([candidate(scope=None), candidate(title="另一条", content="写一段完全不同的东西：{{主题}}", scope="task", taskType="写作")])
        self.assertEqual(code, 0, text)
        self.assertIn("提示词不分适用范围", text)
        result = json.loads(out.read_text(encoding="utf-8"))["candidates"]
        self.assertEqual([c["scope"] for c in result], ["global", "global"])
        self.assertNotIn("taskType", result[1])

    def test_same_rule_in_different_scopes_is_not_merged(self):
        rule = dict(type="rule", title="回答用中文", content="回答使用中文。")
        entries = [candidate(**rule, scope="global"), candidate(**rule, scope="project", project="项目 A"),
                   candidate(**rule, scope="project", project="项目 B"), candidate(**rule, scope="task", taskType="写作"),
                   candidate(**rule, scope="task", taskType="编程"), candidate(**rule, scope="project", project="项目 A")]
        code, _, out = self.finalize(entries)
        self.assertEqual(code, 0)
        result = json.loads(out.read_text(encoding="utf-8"))["candidates"]
        self.assertEqual(len(result), 5)
        self.assertEqual(result[1]["project"], "项目 A")

    def test_duplicates_merged_and_existing_flagged(self):
        rule = candidate(type="rule", title="回答用中文", content="回答使用中文。", ruleCategory="语言", confidence="high", count=12)
        code, text, out = self.finalize([candidate(), candidate(title="小红书改写", count=3), rule])
        self.assertEqual(code, 0)
        self.assertIn("合并成一条", text)
        self.assertIn("可能已经写在已有的规则或库里", text)
        titles = [c["title"] for c in json.loads(out.read_text(encoding="utf-8"))["candidates"]]
        self.assertEqual(titles, ["小红书风格改写", "回答用中文"])

    def test_secrets_and_leftover_specifics(self):
        leaky = candidate(content="用 sk-abcdefghijklmnopqrstuvwxyz123456 调接口，修好 src/app/main.ts 里的 TypeError")
        code, text, out = self.finalize([leaky])
        self.assertEqual(code, 0)
        self.assertIn("已换成 [已隐藏]", text)
        self.assertIn("残留具体信息", text)
        self.assertNotIn("sk-abcdefghij", out.read_text(encoding="utf-8"))

    def test_skill_export_validated(self):
        good = candidate(export={"format": "skill", "skillName": "xhs-rewrite", "skillDescription": "把一段经历改写成小红书文案。在用户要求写小红书时使用。"})
        bad = candidate(title="另一个", content="写一段完全不同的东西：{{主题}}", export={"format": "skill", "skillName": "Claude Helper", "skillDescription": "x"})
        code, text, out = self.finalize([good, bad])
        self.assertEqual(code, 0)
        exports = [c["export"] for c in json.loads(out.read_text(encoding="utf-8"))["candidates"]]
        self.assertEqual(exports[0]["skillName"], "xhs-rewrite")
        self.assertEqual(exports[1], {"format": "md"})
        self.assertIn("Skill 短名不合规", text)


