describe('挑出任务和纠正', () => {
  it('寒暄和命令是噪音', () => {
    expect(isNoise('好的')).toBe(true);
    expect(isNoise('继续')).toBe(true);
    expect(isNoise('/model')).toBe(true);
    expect(isNoise('帮我写个周报')).toBe(false);
  });

  it('短句里带要求才算纠正', () => {
    expect(looksLikeCorrection('太长了，控制在 200 字')).toBe(true);
    expect(looksLikeCorrection('再举一个例子')).toBe(false);
  });

  it('纠正紧跟在任务后面时记到任务上', () => {
    const utterances = extractUtterances({
      key: 'k',
      tool: 'codex',
      messages: [
        { role: 'user', text: '把下面这段改成小红书风格：周末去了咖啡店', at: 1 },
        { role: 'assistant', text: '……', at: 2 },
        { role: 'user', text: '太长了，控制在 200 字', at: 3 },
        { role: 'assistant', text: '……', at: 4 },
        { role: 'user', text: '谢谢', at: 5 },
      ],
    });
    expect(utterances.map((utterance) => utterance.role)).toEqual(['task', 'correction']);
    expect(utterances[0].after).toBe('太长了，控制在 200 字');
    expect(utterances[0].afterId).toBe(utterances[1].id);
  });

  it('拆出指令和要处理的内容', () => {
    expect(splitInstruction('按目标用户、核心功能四列对比：Notion、飞书文档、语雀')).toEqual({
      head: '按目标用户、核心功能四列对比',
      payload: 'Notion、飞书文档、语雀',
    });
    expect(splitInstruction('解释一下闭包').payload).toBe('');
    expect(instructionClauses('太长了，控制在 200 字')).toEqual(['控制在 200 字']);
  });
});

describe('示例对话里提炼出 5 条候选', () => {
  const now = new Date('2026-10-16T15:00:00+08:00').getTime();
  const utterances = sampleConversations(now).flatMap((conversation) => extractUtterances(conversation, true));
  const items = sampleItems(now);
  const candidates = buildCandidates(utterances, items, []);
  const byTitle = Object.fromEntries(candidates.map((candidate) => [candidate.title, candidate]));

  it('数量和顺序', () => {
    expect(candidates.map((candidate) => [candidate.title, candidate.count])).toEqual([
      ['回答用中文', 12],
      ['先给结论，再给理由', 9],
      ['小红书风格改写', 6],
      ['竞品对比', 4],
      ['周报整理', 3],
    ]);
  });

  it('规则来自哪些工具', () => {
    // 次数多的工具排在前面：Codex 7 次，Claude Code 5 次
    expect(byTitle['回答用中文'].tools).toEqual(['codex', 'claude-code']);
    expect(byTitle['回答用中文'].kind).toBe('rule');
    expect(byTitle['先给结论，再给理由'].tools).toEqual(['codex']);
  });

  it('小红书：不一样的内容变成变量，常补的要求合并进模板', () => {
    const candidate = byTitle['小红书风格改写'];
    expect(candidate.kind).toBe('prompt');
    expect(candidate.template).toBe('把下面这段改成小红书风格，控制在 200 字：\n{{内容}}');
    expect(candidate.fixes).toEqual(['控制在 200 字']);
    expect(candidate.fixCount).toBe(4);
    expect(candidate.tools.sort()).toEqual(['chatgpt', 'codex']);
  });

  it('竞品和周报的变量名', () => {
    expect(byTitle['竞品对比'].template).toBe('按目标用户、核心功能、定价、优缺点四列对比：\n{{竞品列表}}');
    expect(byTitle['周报整理'].template).toBe('把这周的工作记录整理成周报：\n{{本周工作}}');
  });

  it('提示词候选不分范围，规则候选要确认范围；只有周报和库里已有的相似', () => {
    expect(candidates.filter((candidate) => candidate.kind === 'prompt').every((candidate) => readScope(candidate).scope === 'global')).toBe(true);
    expect(candidates.filter((candidate) => candidate.kind === 'rule').every((candidate) => readScope(candidate).scope === 'unconfirmed')).toBe(true);
    expect(candidates.filter((candidate) => candidate.similarItemId).map((candidate) => [candidate.title, candidate.similarItemTitle])).toEqual([['周报整理', '周报生成']]);
  });

  it('合并进模板的纠正不再单独算成"回答简洁"', () => {
    expect(candidates.some((candidate) => candidate.title === '回答简洁')).toBe(false);
  });

  it('处理过的候选：签名变了也按相似文字认出来（规则只在同一范围里认）', () => {
    const decisions: Decision[] = [
      { signature: 'rule-chinese', kind: 'rule', status: 'ignored', title: '回答用中文', text: '回答使用中文。', at: now },
      { signature: 'old', kind: 'prompt', status: 'saved', title: '竞品', text: '按目标用户、核心功能、定价、优缺点四列对比：{{竞品列表}}', at: now },
    ];
    const again = buildCandidates(utterances, items, decisions);
    const status = Object.fromEntries(again.map((candidate) => [candidate.title, candidate.status]));
    expect(status['回答用中文']).toBe('ignored');
    expect(status['竞品对比']).toBe('saved');
    expect(status['小红书风格改写']).toBe('new');
  });

  it('同一任务后的纠正成为待确认范围的规则，不自动升级为全局', () => {
    const conversations = [1, 2, 3].map((n) => ({
      key: `codex:${n}`,
      tool: 'codex' as const,
      messages: [
        { role: 'user' as const, text: `帮我把这次的会议记录整理成纪要：第${n}次周会，讨论了上线计划`, at: n * 10 },
        { role: 'assistant' as const, text: '好的', at: n * 10 + 1 },
        { role: 'user' as const, text: '不要用 emoji', at: n * 10 + 2 },
      ],
    }));
    const found = buildCandidates(conversations.flatMap((conversation) => extractUtterances(conversation)), [], []);
    // 次数相同，最近出现的排前面
    expect(found.map((candidate) => [candidate.title, candidate.template])).toEqual([
      ['不用 emoji', '不要使用 emoji。'],
      ['纪要整理', '帮我把这次的会议记录整理成纪要：\n{{会议记录}}'],
    ]);
    expect(readScope(found[0]).scope).toBe('unconfirmed');
  });

  it('同一类每次扫描得到同一个签名', () => {
    const again = buildCandidates([...utterances].reverse(), items, []);
    expect(again.map((candidate) => candidate.id).sort()).toEqual(candidates.map((candidate) => candidate.id).sort());
  });
});
