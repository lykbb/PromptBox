const jsonl = (rows: unknown[]) => rows.map((row) => JSON.stringify(row)).join('\n');

describe('Codex 记录', () => {
  const file = jsonl([
    { timestamp: '2026-10-14T09:00:00Z', type: 'session_meta', payload: { id: 's1', cwd: '/tmp' } },
    {
      timestamp: '2026-10-14T09:00:01Z',
      type: 'response_item',
      payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: '<environment_context>\n<cwd>/tmp</cwd>\n</environment_context>' }] },
    },
    {
      timestamp: '2026-10-14T09:00:01Z',
      type: 'response_item',
      payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: '# AGENTS.md instructions for /tmp\n\n用中文' }] },
    },
    { timestamp: '2026-10-14T09:00:02Z', type: 'event_msg', payload: { type: 'user_message', message: '帮我写个脚本', images: [] } },
    {
      timestamp: '2026-10-14T09:00:02Z',
      type: 'response_item',
      payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: '帮我写个脚本' }] },
    },
    { timestamp: '2026-10-14T09:00:05Z', type: 'response_item', payload: { type: 'function_call', name: 'shell', arguments: '{}' } },
    { timestamp: '2026-10-14T09:00:09Z', type: 'event_msg', payload: { type: 'agent_message', message: 'Here is the script' } },
    { timestamp: '2026-10-14T09:01:00Z', type: 'event_msg', payload: { type: 'user_message', message: '用中文回答' } },
    'not json',
  ]);

  it('用事件里的用户原话，去掉环境信息和规则文件', () => {
    const conversation = parseCodexSession(file, 'codex:a');
    expect(conversation?.messages.map((message) => [message.role, message.text])).toEqual([
      ['user', '帮我写个脚本'],
      ['assistant', 'Here is the script'],
      ['user', '用中文回答'],
    ]);
  });

  it('没有事件时退回到消息记录（早期格式）', () => {
    const old = jsonl([
      { id: 's2', timestamp: '2025-05-01T10:00:00Z', instructions: null },
      { type: 'message', role: 'user', content: [{ type: 'input_text', text: '<user_instructions>x</user_instructions>' }] },
      { type: 'message', role: 'user', content: [{ type: 'input_text', text: '解释一下这个报错' }] },
      { type: 'message', role: 'assistant', content: [{ type: 'output_text', text: '原因是……' }] },
    ]);
    expect(parseCodexSession(old, 'codex:b')?.messages.map((message) => message.text)).toEqual(['解释一下这个报错', '原因是……']);
  });

  it('只有自动注入内容的文件不算对话', () => {
    const injectedOnly = jsonl([
      { type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: '<environment_context>x</environment_context>' }] } },
    ]);
    expect(parseCodexSession(injectedOnly, 'codex:c')).toBeNull();
  });
});

